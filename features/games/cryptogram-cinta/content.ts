export const CRYPTOGRAM_LANGUAGES = ["id", "en"] as const;

export type CryptogramLanguage =
  (typeof CRYPTOGRAM_LANGUAGES)[number];

export const DEFAULT_CRYPTOGRAM_LANGUAGE: CryptogramLanguage = "id";

export function isCryptogramLanguage(
  value: unknown,
): value is CryptogramLanguage {
  return (
    typeof value === "string" &&
    CRYPTOGRAM_LANGUAGES.includes(value as CryptogramLanguage)
  );
}

export function cryptogramLanguageLabel(
  language: CryptogramLanguage,
) {
  return language === "id" ? "Bahasa Indonesia" : "English";
}

