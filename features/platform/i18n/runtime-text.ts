export function localizeRuntimeText(
  locale: AppLocale,
  value: string,
) {
  if (locale === "id" || !value) return value;

  const exact = ENGLISH_MESSAGES[value];
  if (exact) return exact;

  return value.replace(
    /^Pesan maksimal (\d+) karakter\.$/,
    "Messages may contain at most $1 characters.",
  );
}
